#!/usr/bin/env node
// Retire one wave's copies for their owner and admit the owner's packages to the workspace in their place.
//
//   retire-wave --census <census.json> --wave <n> --repo <this repository> --mount <path of the mounted owner forest>
//               --owner-name <owner repository name> [--admitted <admitted.json>] [--hold <name>=<reason>]... [--write]
//
// For every package of the wave that is not held, the copy's own files (not its nested packages, not a repository
// mounted inside it, not a lib/legacy tree inside it) move under <section>/lib/legacy/retired-for-<owner-name>/wave-<n>/<the copy's path>, where
// <section> is lib/emsenn/services/561-group. The owner package of each joins the admitted set, with every package
// it needs that the owner forest defines and this repository then no longer does. The workspace's exclusion block
// for the mount is regenerated from that set: an owner package directory outside it is excluded by its exact path,
// and a subtree holding none of it by the subtree. Relative imports elsewhere in the repository that would now
// resolve into a retired copy, and imports of an export subpath a copy offered that its owner does not, are reported,
// and the run refuses to write while any remain.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const SECTION = "lib/emsenn/services/561-group";
const BEGIN = "  # BEGIN owner admission (generated by retire-wave; do not edit by hand)";
const END = "  # END owner admission";
const OVERRIDES_BEGIN = "  # BEGIN owner overrides (generated by retire-wave; do not edit by hand)";
const OVERRIDES_END = "  # END owner overrides";
const git = (cwd, args) => execFileSync("git", ["-C", cwd, ...args], { encoding: "utf8", maxBuffer: 1 << 30 });

/** name -> directory (repository-relative) of every package in the mounted forest, outside legacy and evidence. */
export function forestPackages(repository, mount, allDirs = new Set()) {
  const found = new Map();
  const visit = (dir) => {
    const rel = relative(repository, dir);
    if (/\/(lib\/legacy|content\/text|vendor|history)(\/|$)/u.test(`/${rel}`)) return;
    let entries;
    try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return; }
    if (entries.some((entry) => entry.isFile() && entry.name === "package.json")) {
      try {
        const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
        // A test fixture's manifest borrows a package's name; it is never where that package lives.
        if (typeof manifest.name === "string" && !found.has(manifest.name) && !/\/(test|fixtures)\//u.test(`/${rel}/`)) found.set(manifest.name, { dir: rel, manifest });
      } catch { /* an unreadable manifest names no package */ }
      allDirs.add(rel);
    }
    for (const entry of entries) if (entry.isDirectory() && entry.name !== "node_modules" && entry.name !== ".git") visit(join(dir, entry.name));
  };
  visit(join(repository, mount));
  return found;
}

/** The exclusion lines that leave exactly `admitted` (repository-relative directories) of the forest in the workspace. */
export function exclusions(mount, packageDirs, admitted) {
  const keep = new Set(admitted);
  const lines = [];
  const holdsKept = (dir) => [...keep].some((kept) => kept === dir || kept.startsWith(`${dir}/`));
  const visit = (dir) => {
    // A subtree glob does not name its own root for every reader (node's path.matchesGlob, which the lockfile
    // freshness check uses, does not), so a package at the root of an excluded subtree is also excluded by name.
    if (!holdsKept(dir)) { if (packageDirs.has(dir)) lines.push(`!${dir}`); lines.push(`!${dir}/**`); return; }
    if (packageDirs.has(dir) && !keep.has(dir)) lines.push(`!${dir}`);
    const children = [...new Set([...packageDirs].filter((other) => other.startsWith(`${dir}/`)).map((other) => other.slice(dir.length + 1).split("/")[0]))].sort();
    for (const child of children) visit(`${dir}/${child}`);
  };
  visit(mount);
  return lines;
}

/** The package names an earlier run already overrode. */
function previousOverrides(text) {
  const at = text.indexOf(OVERRIDES_BEGIN);
  if (at < 0) return [];
  return [...text.slice(at, text.indexOf(OVERRIDES_END, at)).matchAll(/^\s+"([^"]+)": "workspace:\*"$/gmu)].map((match) => match[1]);
}

export function retireWave({ census, wave: number, repository, mount, ownerName, admitted = [], holds: extraHolds = {}, write = false }) {
  // A census records the holds it knows (an ownership gap a package depends on), and a run may add more.
  const holds = { ...(census.holds ?? {}), ...extraHolds };
  const wave = census.waves.find((entry) => entry.wave === number);
  if (!wave) throw new Error(`no wave ${number} in the census`);
  const root = `${SECTION}/lib/legacy/retired-for-${ownerName}/wave-${number}`;
  // Every package directory of the forest, a name held twice included: each is excluded unless admitted.
  const forestDirs = new Set();
  const forest = forestPackages(repository, mount, forestDirs);
  const tracked = git(repository, ["ls-files"]).split("\n").filter(Boolean);
  const packageDirsHere = new Set(tracked.filter((file) => file.endsWith("package.json") && !file.startsWith(`${mount}/`)).map((file) => dirname(file)));
  // A gitlink inside a copy is another repository mounted there: it is never one of the copy's files.
  const gitlinks = git(repository, ["ls-files", "-s"]).split("\n").filter((line) => line.startsWith("160000 ")).map((line) => line.slice(line.indexOf("\t") + 1));
  const moves = [];
  const retired = [];
  for (const name of wave.names) {
    // Held: an open pull request against the copy, or a recorded reason the owner cannot take it yet.
    if (census.openPullRequests?.[name]?.length || holds[name]) continue;
    const entry = census.packages[name];
    for (const copy of entry.copies) {
      const nested = [...packageDirsHere, ...gitlinks].filter((dir) => dir !== copy.path && dir.startsWith(`${copy.path}/`));
      const own = tracked.filter((file) => file.startsWith(`${copy.path}/`)
        && !nested.some((dir) => file === dir || file.startsWith(`${dir}/`))
        && !`/${file.slice(copy.path.length + 1)}`.includes("/lib/legacy/"));
      for (const file of own) moves.push({ from: file, to: `${root}/${file.slice(SECTION.length + 1)}` });
      const owner = forest.get(name)?.dir;
      if (!owner) throw new Error(`the mounted forest defines no ${name}`);
      retired.push({ name, copy: copy.path, owner, retiredTo: `${root}/${copy.path.slice(SECTION.length + 1)}` });
    }
  }
  // Owner packages admitted: those of this wave and earlier, and every package they need that only the forest defines.
  const retiredNames = new Set([...retired.map((row) => row.name)]);
  const definedHere = new Set();
  for (const dir of packageDirsHere) {
    if (dir.includes("/lib/legacy/") || retired.some((row) => row.copy === dir)) continue;
    try { definedHere.add(JSON.parse(readFileSync(join(repository, dir, "package.json"), "utf8")).name); } catch { /* skip */ }
  }
  const admit = new Set(admitted);
  const byDir = new Map([...forest].map(([name, value]) => [value.dir, name]));
  const queue = [...retiredNames, ...admitted.map((dir) => byDir.get(dir)).filter(Boolean)];
  const seen = new Set();
  while (queue.length) {
    const name = queue.pop();
    if (seen.has(name) || !forest.has(name)) continue;
    seen.add(name);
    const found = forest.get(name);
    admit.add(found.dir);
    for (const dep of Object.keys({ ...found.manifest.dependencies, ...found.manifest.peerDependencies })) {
      if (forest.has(dep) && !definedHere.has(dep)) queue.push(dep);
    }
  }
  // Relative imports outside the retiring files that point into what retires.
  const retiringFiles = new Set(moves.map((move) => move.from));
  const broken = [];
  for (const file of tracked) {
    if (!/\.(mjs|js|cjs|ts|mts)$/u.test(file) || retiringFiles.has(file) || file.includes("/lib/legacy/") || file.startsWith(`${mount}/`) || file.includes("/node_modules/")) continue;
    const text = readFileSync(join(repository, file), "utf8");
    for (const match of text.matchAll(/(?:\bfrom|\bimport\s*\(|\bimport|\brequire\s*\()\s*["'](\.{1,2}\/[^"']+)["']/gu)) {
      const target = relative(repository, resolve(repository, dirname(file), match[1]));
      if (retiringFiles.has(target)) broken.push({ file, specifier: match[1], target });
    }
  }
  // Every export subpath a retiring copy offered that code here imports must be one its owner offers too: an owner that
  // dropped one would leave its importers unresolved once the copy retires.
  const subpaths = (manifest) => {
    const exportsField = manifest?.exports;
    if (exportsField === undefined || typeof exportsField === "string") return new Set(["."]);
    const keys = Object.keys(exportsField).filter((key) => key.startsWith("."));
    return new Set(keys.length ? keys : ["."]);
  };
  const lostExports = [];
  for (const row of retired) {
    const copyManifestPath = [join(repository, row.copy, "package.json"), join(repository, row.retiredTo, "package.json")].find((path) => existsSync(path));
    if (!copyManifestPath) continue;
    const offered = subpaths(JSON.parse(readFileSync(copyManifestPath, "utf8")));
    const kept = subpaths(forest.get(row.name)?.manifest);
    for (const subpath of offered) if (!kept.has(subpath)) lostExports.push({ name: row.name, specifier: subpath === "." ? row.name : `${row.name}${subpath.slice(1)}` });
  }
  if (lostExports.length) {
    for (const file of tracked) {
      if (!/\.(mjs|js|cjs|ts|mts)$/u.test(file) || file.includes("/lib/legacy/") || file.startsWith(`${mount}/`) || file.includes("/node_modules/") || file.includes("/data/records/")) continue;
      if (retiringFiles.has(file) || !existsSync(join(repository, file))) continue;
      const text = readFileSync(join(repository, file), "utf8");
      for (const lost of lostExports) if (text.includes(`"${lost.specifier}"`) || text.includes(`'${lost.specifier}'`)) broken.push({ file, specifier: lost.specifier, target: "an export the owner does not offer" });
    }
  }
  const packageDirs = forestDirs;
  const lines = exclusions(mount, packageDirs, [...admit]);
  if (write) {
    if (broken.length) throw new Error(`imports that would break once these copies retire: ${broken.map((row) => `${row.file} -> ${row.specifier}`).join("; ")}`);
    for (const move of moves) {
      mkdirSync(join(repository, dirname(move.to)), { recursive: true });
      git(repository, ["mv", move.from, move.to]);
    }
    const workspace = join(repository, "pnpm-workspace.yaml");
    const text = readFileSync(workspace, "utf8");
    const block = [BEGIN, ...lines.map((line) => `  - "${line}"`), END].join("\n");
    const mountLine = `  - "!${mount}/**"`;
    let next;
    if (text.includes(BEGIN)) next = text.replace(new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&")}[\\s\\S]*?${END}`, "u"), block);
    else if (text.includes(mountLine)) next = text.replace(mountLine, block);
    else throw new Error("pnpm-workspace.yaml holds neither the mount exclusion nor an admission block");
    // Consumers here pin the retired copies' versions; the owner, now the one workspace member of each name, answers them.
    const outside = next.includes(OVERRIDES_BEGIN) ? next.slice(0, next.indexOf(OVERRIDES_BEGIN)) + next.slice(next.indexOf(OVERRIDES_END)) : next;
    // An admitted owner package that pins an exact version the workspace holds at another links the workspace member
    // too, as the drifted pins of #522 do: that package is reconciled into its owner in its own wave.
    const workspaceVersions = new Map();
    for (const dir of [...packageDirsHere, ...admit]) {
      if (dir.includes("/lib/legacy/")) continue;
      try { const m = JSON.parse(readFileSync(join(repository, dir, "package.json"), "utf8")); if (m.name && !workspaceVersions.has(m.name)) workspaceVersions.set(m.name, m.version); } catch { /* skip */ }
    }
    const drifted = [];
    for (const dir of admit) {
      const m = JSON.parse(readFileSync(join(repository, dir, "package.json"), "utf8"));
      for (const [dep, spec] of Object.entries({ ...m.dependencies, ...m.peerDependencies })) {
        if (/^\d+\.\d+\.\d+$/u.test(spec) && workspaceVersions.has(dep) && workspaceVersions.get(dep) !== spec) drifted.push(dep);
      }
    }
    const overridden = [...new Set([...(previousOverrides(next)), ...retired.map((row) => row.name), ...drifted])]
      .filter((name) => !outside.includes(`"${name}": "workspace:*"`)).sort();
    const overrideBlock = [OVERRIDES_BEGIN, ...overridden.map((name) => `  "${name}": "workspace:*"`), OVERRIDES_END].join("\n");
    if (next.includes(OVERRIDES_BEGIN)) next = next.replace(new RegExp(`${OVERRIDES_BEGIN.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&")}[\\s\\S]*?${OVERRIDES_END}`, "u"), overrideBlock);
    else if (/^overrides:\n/mu.test(next)) next = next.replace(/^overrides:\n/mu, `overrides:\n${overrideBlock}\n`);
    else next = `${next.trimEnd()}\n\noverrides:\n${overrideBlock}\n`;
    writeFileSync(workspace, next);
  }
  return { kind: "owner-retirement-wave/v1", wave: number, root, retired, held: holds, moves: moves.length, admitted: [...admit].sort(), exclusions: lines, broken };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const take = (flag) => { const at = args.indexOf(flag); return at < 0 ? undefined : args[at + 1]; };
  for (const flag of ["--census", "--wave", "--repo", "--mount", "--owner-name"]) if (!take(flag)) { process.stderr.write("usage: retire-wave --census <census.json> --wave <n> --repo <dir> --mount <path> --owner-name <name> [--admitted <admitted.json>] [--hold <name>=<reason>]... [--write]\n"); process.exit(2); }
  const admitted = take("--admitted") && existsSync(take("--admitted")) ? JSON.parse(readFileSync(take("--admitted"), "utf8")).admitted : [];
  const holds = Object.fromEntries(args.flatMap((value, at) => (args[at - 1] === "--hold" ? [[value.slice(0, value.indexOf("=")), value.slice(value.indexOf("=") + 1)]] : [])));
  const result = retireWave({ census: JSON.parse(readFileSync(take("--census"), "utf8")), wave: Number(take("--wave")), repository: take("--repo"), mount: take("--mount"), ownerName: take("--owner-name"), admitted, holds, write: args.includes("--write") });
  if (take("--admitted") && args.includes("--write")) writeFileSync(take("--admitted"), `${JSON.stringify({ kind: "owner-admission/v1", mount: take("--mount"), admitted: result.admitted }, null, 1)}\n`);
  process.stdout.write(`${JSON.stringify(result, null, 1)}\n`);
}
